def run(coroutine):
    return asyncio.run(
        coroutine,
        loop_factory=asyncio.SelectorEventLoop if sys.platform == "win32" else None,
    )


@pytest.fixture(scope="session")
def test_database():
    base_url = make_url(get_settings().database_url)
    database_name = "intervai_test_" + uuid4().hex[:16]
    admin_url = base_url.set(drivername="postgresql", database="postgres").render_as_string(
        hide_password=False
    )
    test_url = base_url.set(database=database_name)
    with psycopg.connect(admin_url, autocommit=True) as admin:
        admin.execute(sql.SQL("CREATE DATABASE {}").format(sql.Identifier(database_name)))
    env = {**os.environ, "DATABASE_URL": test_url.render_as_string(hide_password=False)}

    def migrate(target, revision):
        subprocess.run(
            [
                sys.executable,
                "-m",
                "alembic",
                "-c",
                str(ROOT / "backend/alembic.ini"),
                target,
                revision,
            ],
            env=env,
            check=True,
            capture_output=True,
        )

    try:
        migrate("upgrade", "head")
        migrate("downgrade", "base")
        migrate("upgrade", "head")
        yield test_url
    finally:
        # This name was generated by this fixture, and is never read from user configuration.
        assert database_name.startswith("intervai_test_")
        with psycopg.connect(admin_url, autocommit=True) as admin:
            admin.execute(
                sql.SQL("DROP DATABASE {} WITH (FORCE)").format(sql.Identifier(database_name))
            )


class Harness:
    def __init__(self, url):
        self.url = url
        self.cookies = Cookies()
        self.csrf = ""

    def request(self, method, path, **kwargs):
        async def send():
            headers = {"Origin": ORIGIN, **kwargs.pop("headers", {})}
            async with AsyncClient(
                transport=ASGITransport(app),
                base_url="http://test",
                cookies=self.cookies,
            ) as client:
                response = await client.request(method, "/api/v1" + path, headers=headers, **kwargs)
                self.cookies = client.cookies
                return response

        return run(send())

    def register(self, email="candidate@example.com", **values):
        return self.request(
            "POST",
            "/auth/register",
            json={
                "email": email,
                "password": PASSWORD,
                "display_name": "Development Test Candidate",
                **values,
            },
        )

    def login(self, email="candidate@example.com", password=PASSWORD):
        response = self.request("POST", "/auth/login", json={"email": email, "password": password})
        if response.status_code == 200:
            self.csrf = response.json()["csrf_token"]
        return response

    def patch(self, payload, **kwargs):
        return self.request(
            "PATCH",
            "/candidates/me",
            headers={"X-CSRF-Token": self.csrf, **kwargs},
            json=payload,
        )

    def sql(self, statement, parameters=None):
        dsn = self.url.set(drivername="postgresql").render_as_string(hide_password=False)
        with psycopg.connect(dsn, row_factory=dict_row) as connection:
            cursor = connection.execute(statement, parameters)
            return cursor.fetchall() if cursor.description else None


